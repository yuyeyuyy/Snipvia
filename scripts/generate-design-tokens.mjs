import { readFile, writeFile } from 'node:fs/promises';
import { URL } from 'node:url';

// Single palette for renderer CSS and Electron native window surfaces.
const source = new URL('../src/shared/design-tokens.json', import.meta.url);
const output = new URL('../src/renderer/src/design/tokens.css', import.meta.url);
const tokens = JSON.parse(await readFile(source, 'utf8'));
const declarations = (values) => Object.entries(values).map(([name, value]) => `  --${name}: ${value};`).join('\n');
const css = `/* Generated by node scripts/generate-design-tokens.mjs. Edit src/shared/design-tokens.json. */
:root {\n${declarations(tokens.metrics)}\n${declarations(tokens.light)}\n  color-scheme: light;
  --surface: var(--bg-window); --canvas: var(--bg-window); --sidebar: var(--bg-nav);
  --line: var(--border-subtle); --line-strong: var(--border-default);
  --ink: var(--text-primary); --secondary-ink: var(--text-secondary); --muted-ink: var(--text-muted); --accent-tint: var(--bg-selected);
}
:root[data-theme='dark'] {\n${declarations(tokens.dark)}\n  color-scheme: dark;\n}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {\n${declarations(tokens.dark)}\n    color-scheme: dark;\n  }
}
html { font-family: var(--font-ui); font-synthesis: none; -webkit-font-smoothing: antialiased; color: var(--text-primary); }
html, body, #root { background: var(--bg-window); }
html.floating-window, .floating-window body, .floating-window #root,
html.capture-window, .capture-window body, .capture-window #root { background: transparent; }
`;
await writeFile(output, css);
